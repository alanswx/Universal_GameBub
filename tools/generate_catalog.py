#!/usr/bin/env python3
"""Assemble pinned Universal MRAs from owned ZIPs; emit ROM-free metadata.

ROM bytes stay in ignored scratch/roms. Both sparse split and merged sets
are matched by CRC; offset/length slices are applied only after validation.
The two malformed Devil Zone attributes receive an exact checked XML fix.
"""
import argparse,hashlib,json,zipfile,zlib,xml.etree.ElementTree as ET
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DEFAULT_DIRS=[Path.home()/'mister/cardbackup/MiSTer_Data/games/mame',Path.home()/'Downloads/mame-merged/mame-merged']
def corrected_mra(path):
 text=path.read_text()
 if path.name in ('Devil Zone.mra','Devil Zone (Easier).mra'):
  assert text.count('Use Coin A & B')==1,'Upstream Devil Zone correction needs review'
  text=text.replace('Use Coin A & B','Use Coin A &amp; B')
 return text

def generate(dirs,check=False):
 games=[];identities={};archives={};unavailable=[]
 def chips(zips,crc):
  for z in zips:
   for folder in dirs:
    path=folder/z
    if not path.is_file():continue
    if path not in archives:archives[path]=zipfile.ZipFile(path)
    archive=archives[path]
    for info in archive.infolist():
     if info.CRC==int(crc,16):
      data=archive.read(info);assert zlib.crc32(data)==int(crc,16)
      return data
  raise ValueError(f'Missing chip CRC {crc}, ZIPs {zips}')
 def output(path,text):
  if check:assert path.read_text()==text,f'Stale {path}'
  else:
   path.parent.mkdir(parents=True,exist_ok=True)
   if not path.is_file() or path.read_text()!=text:path.write_text(text)
 for path in sorted((ROOT/'upstream/Arcade-Universal_MiSTer/releases').rglob('*.mra')):
  text=corrected_mra(path);xml=ET.fromstring(text);rom=xml.find("rom[@index='0']")
  zips=rom.get('zip').split('|');parts=[];chunks=[]
  missing=None
  for part in rom:
   assert part.tag=='part' and not set(part.attrib)-{'name','crc','repeat','offset','length'},'Unsupported MRA operation'
   repeat=int(part.get('repeat','1'),0);assert repeat>0
   if part.get('name'):
    crc=part.get('crc').lower()
    try:raw=chips(zips,crc)
    except ValueError as e:missing=str(e);break
    offset=int(part.get('offset','0'),0);length=int(part.get('length',str(len(raw)-offset)),0)
    assert offset>=0 and length>0 and offset+length<=len(raw)
    data=raw[offset:offset+length]
    parts.append(dict(name=part.get('name'),crc=crc,size=len(raw),offset=offset,length=length,repeat=repeat))
   else:
    assert not set(part.attrib)-{'repeat'}
    data=bytes.fromhex(part.text);parts.append(dict(fill=data.hex(),repeat=repeat))
   chunks += [data]*repeat
  if missing:
   unavailable.append(dict(mra=str(path.relative_to(ROOT)),name=xml.findtext('name'),reason=missing));continue
  data=b''.join(chunks);cfg=bytes.fromhex(xml.find("rom[@index='1']/part").text);assert len(cfg)==64
  assert cfg[0]<=17,'TMS games have no recipes at this pin'
  dips=list(bytes.fromhex(xml.find('switches').get('default').replace(',',' ')))
  assert len(dips)<=8
  key=xml.findtext('setname');crc=f'{zlib.crc32(data):08x}';identity=(len(data),crc)
  signature=(cfg.hex(),tuple(dips))
  if identity in identities:assert identities[identity]==signature,f'Conflicting full-image identity: {key}'
  identities[identity]=signature
  local='gamedb/mra/'+str(path.relative_to(ROOT/'upstream/Arcade-Universal_MiSTer/releases'))
  game=dict(key=key,name=xml.findtext('name'),rom_filename=path.stem+'.rom',set=key,zips=zips,size=len(data),crc32=crc,sha256=hashlib.sha256(data).hexdigest(),config=list(cfg),dips=dips,parts=parts,mra=local,status='test2 baseline hardware-confirmed' if key=='ladybug' else 'test candidate; hardware pending',variant=cfg[0])
  games.append(game);output(ROOT/local,text)
  out=ROOT/'scratch/roms';out.mkdir(parents=True,exist_ok=True);(out/(key+'.rom')).write_bytes(data)
 for a in archives.values():a.close()
 assert len(games)<255
 # Keep Lady Bug index 0 for the known baseline; other IDs are stable by setname.
 games.sort(key=lambda g:(g['key']!='ladybug',g['key']))
 assert len({g['crc32'] for g in games})==len(games),'CRC-only case grouping needs review'
 assert len({g['rom_filename'].casefold() for g in games})==len(games),'SD filenames collide'
 for i,g in enumerate(games):g['id']=i
 output(ROOT/'docs/UNAVAILABLE_RECIPES.json',json.dumps(unavailable,indent=2)+'\n')
 for g in unavailable:print('UNAVAILABLE: '+g['name']+': '+g['reason'])
 output(ROOT/'gamedb/games.json',json.dumps(games,indent=2)+'\n')
 sv='// Generated by tools/generate_catalog.py; recipes/checksums only.\npackage universal_catalog;\n'
 sv+=f'localparam integer GAME_COUNT={len(games)}, GAME_MAX_SIZE={max(g["size"] for g in games)};\n'
 sv+="function automatic [7:0] identify_game(input [31:0] crc,input [31:0] size);\n identify_game=8'hff;\n case(crc)\n"
 emitted=set()
 for g in games:
  k=(g['size'],g['crc32'])
  if k in emitted:continue
  emitted.add(k);sv+=f" 32'h{g['crc32']}: if(size=={g['size']})identify_game=8'd{g['id']};\n"
 sv+=' default: ;\n endcase\nendfunction\n'
 sv+='function automatic [511:0] game_config(input [7:0] game_id);\n case(game_id)\n'
 for g in games:sv+=f" {g['id']}:game_config=512'h{int.from_bytes(bytes(g['config']),'little'):0128x};\n"
 sv+=" default:game_config=0;\n endcase\nendfunction\n"
 sv+='function automatic [7:0] config_byte(input [7:0] game_id,input integer index);\n config_byte=8\'(game_config(game_id)>>(index*8));\nendfunction\n'
 sv+='function automatic [63:0] game_dips(input [7:0] game_id);\n case(game_id)\n'
 for g in games:sv+=f" {g['id']}:game_dips=64'h{int.from_bytes(bytes(g['dips']+[255]*(8-len(g['dips']))),'little'):016x};\n"
 sv+=" default:game_dips=64'hffffffffffffffff;\n endcase\nendfunction\nendpackage\n"
 output(ROOT/'rtl/gamebub/game_catalog.sv',sv)
 print(f'{len(games)} recipes, {len(identities)} distinct full images; max {max(g["size"] for g in games)} bytes')
 return games

def main():
 p=argparse.ArgumentParser();p.add_argument('--mame-dir',action='append',type=Path);p.add_argument('--check',action='store_true');a=p.parse_args()
 generate(a.mame_dir or DEFAULT_DIRS,a.check)
if __name__=='__main__':main()
